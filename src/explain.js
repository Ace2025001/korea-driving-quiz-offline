  function extract(text,rules){
    return unique(rules.flatMap(r=>[...text.matchAll(r)].map(x=>neat(x[0]))));
  }
  function facts(raw){
    const tokens=extract(raw,[...cueRules,...humanFacts]);
    return tokens.filter(t=>!['只要','只有','不得','必须','除外','以下','以上'].includes(t)).slice(0,8);
  }
  function decision(q,mode){
    const topic=theme(q), show=q.prompt_zh.split(/\n/).slice(1)
      .map(x=>neat(x.replace(/^[■▶●※]\s*/,''))).filter(Boolean).slice(0,4);
    const key=unique([...(topic?.match?[topic.match]:[]),...facts(q.prompt_zh),...coach.keyTerms(q)])
      .filter(x=>x!==mode.word&&x.length>1).slice(0,6);
    const answers=q.options.filter(o=>q.correct_answers.includes(o.id));
    let optionFacts=unique(answers.flatMap(o=>facts(o.text))).slice(0,4);
    if(!optionFacts.length){
      optionFacts=answers.map(o=>neat(o.text.split(/[，。；！？\n]/)[0])).filter(Boolean).map(x=>x.length>42?x.slice(0,42)+'…':x);
    }
    const specific=show.length?'比较图注给出的场景和各选项的动作，别脱离本题图示套用口诀。':
      q.media_kind==='video'?'先看完整视频：暂停定位参与者、信号和路线发生变化的那一刻。':
      q.media_kind==='image'?'先在图中指出具体的车道、灯或标志，再和题干及选项比对。':
      mode.kind==='reverse'?'检查是否有一项把适用对象、条件、义务强弱或数字改掉了。':
      mode.kind==='risk'?'先选会造成路线冲突或来不及处置的风险；别把危险题当成动作题。':'看清题目限定的人、车辆或道路，再比较对应的动作、术语或数值。';
    return {key,show,optionFacts,topic,specific};
  }
