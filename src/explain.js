  function theme(q){
    // 先信题干和图注；只在题干没提供主题时，用原题标签或正确选项做辅助。
    const stem=q.prompt_zh;
    const opt=q.options.filter(o=>q.correct_answers.includes(o.id)).map(o=>o.text).join(' ');
    const score=(name,re)=>{
      const normal=stem.match(re)?.[0]||'';
      const inRight=opt.match(re)?.[0]||'';
      let s=(normal?50+Math.min(normal.length,14):0)+(inRight?12+Math.min(inRight.length,10):0);
      if((name==='酒驾或药驾')&&/酒精浓度|醉酒|饮酒|酒驾/.test(stem))s+=25;
      if((name==='儿童校车')&&/校车/.test(stem))s+=30;
      if((name==='学校附近的行人')&&/儿童保护|学校门前/.test(stem))s+=28;
      if((name==='无保护左转')&&normal)s+=30;
      if((name==='红灯与专用信号')&&normal)s+=28;
      if((name==='环岛与导向')&&normal)s+=25;
      if((name==='报警与紧急车')&&/(紧急任务|警灯|警笛|正在通过.+救护车)/.test(stem))s+=25;
      if((name==='酒驾或药驾')&&/处罚标准|处罚为/.test(stem))s-=30;
      return s;
    };
    let hit=null,max=0;
    for(const [name,re,tip] of patterns){
      const s=score(name,re);
      if(s>max){hit={name,match:stem.match(re)?.[0]||'',tip};max=s;}
    }
    return hit;
  }
